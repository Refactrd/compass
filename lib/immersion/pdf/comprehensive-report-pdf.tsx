import { Document, Page, Text, View } from "@react-pdf/renderer";

import type { Bottleneck } from "@/lib/immersion/bottleneck-extraction";
import type { WorkflowDiagram } from "@/lib/immersion/diagram-schema";
import { buildEngagementRoadmap } from "@/lib/immersion/roadmap";
import type { Solution } from "@/lib/immersion/opportunity-mapping";
import { DiagramSection, pdfStyles, ReportFooter, ReportLogo } from "@/lib/immersion/pdf/shared";
import { bracketFor, computeWorkflowScore, engagementBracket } from "@/lib/immersion/workflow-score";

/**
 * The Comprehensive Report: one collated document across every Department in
 * a finished Engagement (CLAUDE.md, Phase 2 days 10-11).
 *
 * Restructured after a real dry run: a 90-day roadmap repeated per
 * department read as noise once there were several of them, each with its
 * own near-identical phase labels. One organization-wide roadmap at the end
 * (Day 0-30 / 30-60 / 60-90, each a table of every department's solutions
 * due in that window) says the same thing once, in the order a reader
 * actually wants it in across a multi-department engagement. The Summary
 * ahead of it is new: real prose synthesizing the whole engagement, not a
 * department-by-department recap, since that is what the rest of the report
 * already is.
 *
 * Deliberately condensed where the department-level PDF is already
 * thorough: solution rationale and grounding both live in that document.
 * This report's department pages show the before and after diagrams only;
 * every solution itself now lives once, in its roadmap phase at the end,
 * not duplicated per department the way the old per-department roadmap did.
 */

export type ReportDepartment = {
  name: string;
  beforeDiagram: WorkflowDiagram;
  afterDiagram: WorkflowDiagram;
  solutions: Solution[];
  bottlenecks: Bottleneck[];
};

export function ComprehensiveReportPdfDocument({
  clientName,
  date,
  departments,
  summary,
}: {
  clientName: string;
  date: string;
  departments: ReportDepartment[];
  /** Generated by lib/immersion/comprehensive-summary.ts. Two to four
   * paragraphs, already trimmed; split on blank lines for rendering. */
  summary: string;
}) {
  const departmentScores = departments.map(
    (d) => computeWorkflowScore(d.bottlenecks.length).score,
  );
  const overallBracket = engagementBracket(departmentScores);
  const engagementRoadmap = buildEngagementRoadmap(departments);
  const summaryParagraphs = summary.split(/\n{2,}/).filter((p) => p.trim());

  return (
    <Document>
      <Page size="A4" style={pdfStyles.page}>
        <ReportLogo />
        <Text style={pdfStyles.h1}>Comprehensive Report</Text>
        <Text style={pdfStyles.meta}>{`${clientName} · ${date}`}</Text>

        <View style={pdfStyles.phaseBlock} wrap={false}>
          <Text style={pdfStyles.h3}>
            {`Overall workflow health: ${overallBracket.grade} (${overallBracket.label})`}
          </Text>
          <Text style={{ fontSize: 9, opacity: 0.7, marginTop: 2 }}>
            {overallBracket.description} The mean of each department&apos;s own
            bracket below, based on the number of bottlenecks identified
            during that department&apos;s interview. A computed indicator, not a
            measured or sourced figure.
          </Text>
        </View>

        <Text style={pdfStyles.h2}>Departments covered</Text>
        {departments.map((department, i) => {
          const bracket = bracketFor(computeWorkflowScore(department.bottlenecks.length).score);
          return (
            <Text
              key={`toc-${i}`}
              style={pdfStyles.tocEntry}
            >{`${i + 1}. ${department.name} — health ${bracket.grade} (${bracket.label})`}</Text>
          );
        })}

        <ReportFooter clientName={clientName} />
      </Page>

      {departments.map((department, deptIndex) => {
        const bracket = bracketFor(computeWorkflowScore(department.bottlenecks.length).score);
        const prefix = `dept-${deptIndex}`;

        return (
          <Page key={prefix} size="A4" style={pdfStyles.page} wrap>
            <Text style={pdfStyles.h1}>{department.name}</Text>
            <Text style={pdfStyles.meta}>
              {`Workflow health: ${bracket.grade} (${bracket.label})`}
            </Text>

            <DiagramSection
              title="Current workflow"
              diagram={department.beforeDiagram}
              keyPrefix={`${prefix}-before`}
            />
            <DiagramSection
              title="Transformed workflow"
              diagram={department.afterDiagram}
              keyPrefix={`${prefix}-after`}
            />

            <ReportFooter clientName={clientName} />
          </Page>
        );
      })}

      <Page size="A4" style={pdfStyles.page} wrap>
        <Text style={pdfStyles.h1}>Summary</Text>
        {summaryParagraphs.length === 0 ? (
          <Text style={{ fontSize: 9, opacity: 0.6 }}>No summary could be generated.</Text>
        ) : (
          summaryParagraphs.map((paragraph, i) => (
            <Text key={`summary-${i}`} style={pdfStyles.summaryParagraph}>
              {paragraph.trim()}
            </Text>
          ))
        )}

        <Text style={[pdfStyles.h2, { marginTop: 24 }]}>Roadmap</Text>
        {engagementRoadmap.phases.length === 0 ? (
          <Text style={{ fontSize: 9, opacity: 0.6 }}>
            No grounded solutions to sequence across this engagement.
          </Text>
        ) : (
          engagementRoadmap.phases.map((phase, phaseIndex) => (
            <View key={`phase-${phaseIndex}`} wrap={false}>
              <Text style={pdfStyles.h3}>{`${phase.label}, ${phase.rangeDays}`}</Text>
              <View style={pdfStyles.table}>
                <View style={pdfStyles.tableHeaderRow}>
                  <Text style={pdfStyles.tableHeaderCellSolution}>Solutions</Text>
                  <Text style={pdfStyles.tableHeaderCellTime}>Time saved</Text>
                </View>
                {phase.entries.map((entry, entryIndex) => (
                  <View key={`phase-${phaseIndex}-entry-${entryIndex}`} style={pdfStyles.tableRow}>
                    <View style={pdfStyles.tableCellSolution}>
                      <Text style={pdfStyles.tableCellSolutionDept}>{entry.departmentName}</Text>
                      <Text>{entry.solution.title}</Text>
                    </View>
                    <Text style={pdfStyles.tableCellTime}>
                      {entry.solution.timeSavedEstimate ?? "Not yet quantified"}
                    </Text>
                  </View>
                ))}
              </View>
            </View>
          ))
        )}

        <ReportFooter clientName={clientName} />
      </Page>
    </Document>
  );
}
